describe("handle policy", () => {
  it("preserves the blocklist sections", () => {
    expect(BLOCKLIST_INFRASTRUCTURE).toEqual(FIXTURE_INFRASTRUCTURE);
    expect(BLOCKLIST_IMPERSONATION).toEqual(FIXTURE_IMPERSONATION);
    expect(BLOCKLIST_OFFENSIVE).toEqual(FIXTURE_OFFENSIVE);
    expect(BLOCKLIST_INFRASTRUCTURE.length).toBe(249);
    expect(BLOCKLIST_IMPERSONATION.length).toBe(53);
    expect(BLOCKLIST_OFFENSIVE.length).toBe(63);
    expect(BLOCKLIST.size).toBe(365);
  });

  it("reserves short labels and blocks exact labels", () => {
    for (const label of ["a", "ab", "admin", "knot", "pds", "www", "solpbc", "rook", "swastika"]) {
      expect(isReservedOrBlocked(label)).toBe(true);
    }

    for (const label of ["myagent", "abc", "lifecycle"]) {
      expect(isReservedOrBlocked(label)).toBe(false);
    }
  });
});
